"""Reference data from a published version (one-time, reproducible).

Splits a public version's dataset into
  * ``labels.jsonl.gz``  — per-article section/political labels keyed by canonical-URL id
                           (training data for the classifiers);
  * ``events.json``      — hand-checked events (locked, members as article ids) and every
                           event's topic labels (training data for the topic classifier);
  * ``editorial.json``   — supplied editorial material carried unchanged: outlet profiles,
                           parties, bias definitions, rules, narrative coding, literature…

Nothing here is regenerated by the pipeline; it is the human/supplied layer the algorithms extend.
"""
from __future__ import annotations

import gzip
import json
import re
from pathlib import Path

from .store import article_id

# Supplied/human keys carried as-is. Everything else is recomputed from the corpus.
EDITORIAL_KEYS = ("S", "R", "B", "F", "P", "X", "N", "I", "G", "L", "BR", "BRM", "CL", "NW")


def dataset_from_html(html_path: Path) -> dict:
    html = html_path.read_text(encoding="utf-8")
    m = re.search(r'<script type="application/json" id="cm-data">(.*?)</script>', html, re.S)
    if not m:
        raise ValueError("no cm-data block in the supplied HTML")
    return json.loads(m.group(1))


def build_reference(dataset: dict, out: Path) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    old_to_new = {a["i"]: article_id(a["u"]) for a in dataset["A"]}
    with open(out / "labels.jsonl.gz", "wb") as raw, gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as fh:
        for a in dataset["A"]:
            fh.write((json.dumps({"id": old_to_new[a["i"]], "s": a["s"], "c": a["c"], "p": a["p"], "e": a.get("e", [])},
                                 ensure_ascii=False, separators=(",", ":")) + "\n").encode())
    hand, topics = [], []
    for e in dataset["E"]:
        members = [old_to_new[i] for i in e["a"] if i in old_to_new]
        topics.append({"members": members, "tp": e.get("tp") or []})
        if e.get("hand"):
            keep = {k: v for k, v in e.items() if k not in ("a", "rep", "i")}
            keep["members"] = members
            keep["rep"] = {old_to_new[k]: old_to_new[v] for k, v in (e.get("rep") or {}).items()
                           if k in old_to_new and v in old_to_new}
            keep["refId"] = e["i"]
            hand.append(keep)
    (out / "events.json").write_text(json.dumps({"hand": hand, "topics": topics}, ensure_ascii=False))
    editorial = {k: dataset[k] for k in EDITORIAL_KEYS if k in dataset}
    # The narrative map refers to events by their 4.0 ids; keep a member map so exports can relink.
    editorial["_eventMembers"] = {e["i"]: [old_to_new[i] for i in e["a"] if i in old_to_new]
                                  for e in dataset["E"]}
    editorial["_topicNames"] = {t["k"]: t["n"] for t in dataset.get("TP", [])}
    editorial["_feeds"] = dataset.get("FD", [])
    editorial["_themes"] = dataset.get("ADV", {}).get("topics", {}).get("themes", [])
    (out / "editorial.json").write_text(json.dumps(editorial, ensure_ascii=False))
    return {"labels": len(old_to_new), "hand": len(hand), "topics": len(topics),
            "editorial": sorted(editorial)}
